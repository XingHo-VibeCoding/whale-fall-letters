-- db/test-data-drop.sql —— 删掉压测帖子（跑完 test-data-create.sql 之后用）
-- ------------------------------------------------------------
-- 一条 DELETE 清干净，靠的是统一前缀 post-load。
-- 为什么会有人跑这个文件：压测帖子是**真数据**，不删会一直挂在线上论坛里，
-- 谁都能刷到「压测书 3721」这种莫名其妙的帖子。
--
-- 怎么执行：CloudBase 控制台 → SQL 型数据库 → SQL 编辑器，整段粘贴执行。
--
-- ⚠️ 这是硬删除（不是软删除）：行真的从表里消失，捞不回来。
--    但对象只有压测数据，删错了重新跑 create 就有了，可接受。
--    千万**别把 WHERE 去掉** —— 没有 WHERE 的 DELETE 会清空整个帖子表。
-- ============================================================

-- 先看一眼要删多少（心里有数再动手）
SELECT count(*) AS "即将删除的篇数" FROM posts WHERE "id" LIKE 'post-load%';

-- 真删
DELETE FROM posts WHERE "id" LIKE 'post-load%';

-- 删完自查：应该回 0
SELECT count(*) AS "剩余压测帖" FROM posts WHERE "id" LIKE 'post-load%';
